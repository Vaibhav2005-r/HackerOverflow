#!/usr/bin/env bash
# Concatenates the migrations into ONE file you can paste into the Supabase dashboard (SQL Editor → New query → Run).
# Use this when you don't have the CLI/DB password handy. Seed data is separate: supabase/seed.sql (optional).
set -euo pipefail
cd "$(dirname "$0")"
{
  echo "-- Raksha: full schema (generated by supabase/build-setup.sh — do not edit). Safe to run once on a fresh project."
  for f in migrations/*.sql; do echo; echo "-- ===== $f ====="; cat "$f"; done
} > setup.sql
echo "wrote supabase/setup.sql ($(wc -l < setup.sql) lines)"
